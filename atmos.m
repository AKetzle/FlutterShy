function [rho,p,T,a,mu]=atmos(h)
%global rho p T a mu
%h=0:1000:232939.8;
format short g
g=32.174; % gravitational acceleration, ft/s^2
gamma=1.4; % air ratio of specific heats
R=1716.488; % universal gas constant, ft*lb/slug*R

T0 = 518.688; % air temeprature, Rankine
P0 = 2116.2; % air pressure, lb/ft^2
rho0 = 0.0023769; % air density, slug/ft^3
beta0 = -0.00356616; % temeprature lapse rate, R/ft
mu0 = 3.7373e-7; % dynamic viscosity, lb*s/ft^2

h1 = 36089.2; % ft
T1 = 389.97;
P1 = 472.67;
rho1 = 0.000706121;
beta1 = 0;

h2 = 65616.8;
T2 = 389.97;
P2 = 114.346;
rho2 = 0.000170836;
beta2 = 0.00054864;

h3 = 104986.9;
T3 = 411.57;
P3 = 18.129;
rho3 = 0.00002566374;
beta3 = 0.00153619;

h4 = 154199.5;
T4 = 487.17;
P4 = 2.31634;
rho4 = 0.0000027702;
beta4 = 0;

h5 = 167322.8;
T5 = 487.17;
P5 = 1.39806;
rho5 = 0.00000167199;
beta5 = -0.00153619;

h6 = 232939.6;
T6 = 386.67;
P6 = 0.0826321;
rho6 = 0.000000124605;
beta6 = -0.00109728;

% Initialize T, rho, and p to size of h
T = zeros(size(h));
rho = zeros(size(h));
p = zeros(size(h));

% For h>=0 & h<36089.2
% if h>=0 && h<36089.2;
    T(h>=0 & h<36089.2) = T0+beta0*h(h>=0 & h<36089.2);
    rho(h>=0 & h<36089.2)=rho0*(1+beta0/T0*h(h>=0 & h<36089.2)).^(-g/(beta0*R)-1);
    p(h>=0 & h<36089.2)=P0*(1+beta0/T0*h(h>=0 & h<36089.2)).^(-g/(beta0*R));
    
% For h>=36089.2 & h<=65616.8
    T(h>=36089.2 & h<=65616.8)=389.97;
    rho(h>=36089.2 & h<=65616.8)=rho1.*exp(-(g.*(h(h>=36089.2 & h<=65616.8)-36089.2)./(R*T2)));
    p(h>=36089.2 & h<=65616.8)=P1*exp(-(g.*(h(h>=36089.2 & h<=65616.8)-36089.2)./(R*T2)));

% For h>65616.8 & h<=104986.9
    T(h>65616.8 & h<=104986.9)=T2+beta2*(h(h>65616.8 & h<=104986.9)-65616.8);
    p(h>65616.8 & h<=104986.9)=P2*(1+beta2/T2*(h(h>65616.8 & h<=104986.9)-65616.8)).^(-g/(beta2*R));
    rho(h>65616.8 & h<=104986.9)=rho2*(1+beta2/T2*(h(h>65616.8 & h<=104986.9)-65616.8)).^(-g/(beta2*R)-1);

% For h>104986.9 & h<=154199.5
    T(h>104986.9 & h<=154199.5)=T3+beta3*(h(h>104986.9 & h<=154199.5)-104986.9);
    p(h>104986.9 & h<=154199.5)=P3*(1+beta3/T3*(h(h>104986.9 & h<=154199.5)-104986.9)).^(-g/(beta3*R));
    rho(h>104986.9 & h<=154199.5)=rho3*(1+beta3/T3*(h(h>104986.9 & h<=154199.5)-104986.9)).^(-g/(beta3*R)-1);

% For h>154199.5 & h<=167322.8
    T(h>154199.5 & h<=167322.8)=T4+beta4*(h(h>154199.5 & h<=167322.8)-154199.5);
    p(h>154199.5 & h<=167322.8)=P4*exp(-g*(h(h>154199.5 & h<=167322.8)-154199.5)./(R*T4));
    rho(h>154199.5 & h<=167322.8)=rho4*exp(-g*(h(h>154199.5 & h<=167322.8)-154199.5)./(R*T4));

% For  h>167322.8 & h<=232939.6   
    T(h>167322.8 & h<=232939.6)=T5+beta5*(h(h>167322.8 & h<=232939.6)-167322.8);
    p(h>167322.8 & h<=232939.6)=P5*(1+beta5/T5*(h(h>167322.8 & h<=232939.6)-167322.8)).^(-g/(beta5*R));
    rho(h>167322.8 & h<=232939.6)=rho5*(1+beta5/T5*(h(h>167322.8 & h<=232939.6)-167322.8)).^(-g/(beta5*R)-1);

% For h>232939.6 & h<=278386
    T(h>=232939.6)=T6+beta6*(h(h>=232939.6)-232939.6);
    p(h>=232939.6)=P6*(1+beta6/T6*(h(h>=232939.6)-232939.6)).^(-g/(beta6*R));
    rho(h>=232939.6)=rho6*(1+beta6/T6*(h(h>=232939.6)-232939.6)).^(-g/(beta6*R)-1);
% end
a=sqrt(gamma*R.*T);
mu=3.7373e-7.*((T./518.67).^1.5.*((518.67+198.72)./(T+198.72)));

